
"""Return deterministic structured research output without API calls."""

import html
import json

from src.llm.base import BaseLLMClient, LLMResponse


class ResearchMockLLMClient(BaseLLMClient):
    """Generate predictable research output for development and testing."""

    def generate(self, prompt: str) -> LLMResponse:
        if not prompt or not prompt.strip():
            raise ValueError("Prompt cannot be empty.")

        marker = "Research the following topic carefully:\n\n"

        if marker not in prompt:
            raise ValueError(
                "Research prompt does not contain the expected topic marker."
            )

        topic = prompt.split(marker, 1)[1].split(
            "\n\nInstructions:", 1
        )[0].strip()

        opening_tag = "<UNTRUSTED_INPUT>"
        closing_tag = "</UNTRUSTED_INPUT>"

        if not topic.startswith(opening_tag):
            raise ValueError(
                "Research topic is missing its opening untrusted-input tag."
            )

        if not topic.endswith(closing_tag):
            raise ValueError(
                "Research topic is missing its closing untrusted-input tag."
            )

        topic = topic[len(opening_tag):-len(closing_tag)].strip()
        topic = html.unescape(topic)

        if not topic:
            raise ValueError("Research topic cannot be empty.")

        response = {
            "agent_name": "ResearchAgent",
            "status": "completed",
            "topic": topic,
            "summary": (
                "A simulated research response was generated "
                "for development and testing."
            ),
            "findings": [
                {
                    "finding": (
                        f"Research topic received: {topic}"
                    ),
                    "evidence": (
                        "This is synthetic demonstration evidence "
                        "generated by the deterministic mock client. "
                        "It is not independently verified."
                    ),
                    "confidence_score": 0.5,
                }
            ],
            "missing_information": [
                (
                    "Independent source verification is not performed "
                    "by this mock client."
                )
            ],
        }

        return LLMResponse(
            content=json.dumps(response),
            model="mock-research-llm",
            is_mock=True,
        )
